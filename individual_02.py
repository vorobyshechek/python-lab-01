# Индивидуальное задание 2, вариант 9
# Ввести четырёхзначное число n.
# Выполнить циклический сдвиг цифр влево: первая цифра становится последней.

n = int(input("Введите четырёхзначное число: "))

d1 = n // 1000          # тысячи
d2 = (n // 100) % 10    # сотни
d3 = (n // 10) % 10     # десятки
d4 = n % 10             # единицы

result = d2 * 1000 + d3 * 100 + d4 * 10 + d1

print(f"Результат: {result}")